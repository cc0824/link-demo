CREATE TABLE IF NOT EXISTS product (
 id BIGINT PRIMARY KEY, title VARCHAR(200), description VARCHAR(500), image_ref VARCHAR(100),
 status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'OFF_SHELF')),
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS short_link (
 link_key VARCHAR(11) PRIMARY KEY, product_id BIGINT NOT NULL,
 sharer_id VARCHAR(64) NOT NULL, channel VARCHAR(32) NOT NULL CHECK (channel IN ('wechat','moments','other')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uq_link_business UNIQUE(product_id, sharer_id, channel)
);
CREATE INDEX IF NOT EXISTS idx_link_product ON short_link(product_id);
CREATE TABLE IF NOT EXISTS visit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 link_key VARCHAR(11) NOT NULL REFERENCES short_link(link_key), visitor_hash CHAR(64) NOT NULL,
 visited_at TIMESTAMP WITH TIME ZONE NOT NULL, bucket_start BIGINT NOT NULL,
 CONSTRAINT uq_visit_bucket UNIQUE(link_key, visitor_hash, bucket_start)
);
CREATE INDEX IF NOT EXISTS idx_visit_time ON visit_event(visited_at, link_key, visitor_hash);
CREATE TABLE IF NOT EXISTS app_meta (meta_key VARCHAR(64) PRIMARY KEY, meta_value VARCHAR(200) NOT NULL);
